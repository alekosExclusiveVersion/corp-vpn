#!/bin/bash

# Проверка битых маршрутов Karing (детектор, ТОЛЬКО ЧТЕНИЕ).
#
# Два класса проблем, оба лечатся удалением host-маршрута:
#   A) fake-IP как НАЗНАЧЕНИЕ: 198.20.0.11 → 192.168.128.1 → en0.
#      Такой /32 «живёт» только внутри utun; через физический интерфейс пакет
#      уходит в корп. LAN и гаснет (домен через Karing = 000, с реальным IP = 200).
#      Историческая причина — старт Karing, когда default ещё шёл через старый шлюз.
#   C) fake-IP как ШЛЮЗ: 212.41.11.239 → 198.20.0.35 → en0 (инцидент p7ru5,
#      30.09.2026). Назначение реальное, шлюз фантомный: ARP-записи для
#      198.20.0.35 не существует, поэтому пакет физическому интерфейсом
#      fake-IP доставлен быть не может. Соседний 212.41.10.102 из того же /16
#      в это время работал через utun — то есть дело было в маршруте, не в сервере.
#
# Использование:
#   corp-routes-check.sh             показать что найдено (exit=1 если есть битые)
#   corp-routes-check.sh --sudo-cmd  вывести готовые sudo-команды (без запуска)
#
# Скрипт НИЧЕГО не изменяет (только читает таблицу маршрутов).

# Пул fake-IP Karing: 198.18.0.0/15 и 198.20.0.0/15 (совпадает с FAKEIP_ROUTES
# в corp-routes-clean.sh — раньше здесь был только 198.20/15, из-за чего
# маршруты через второй пул проходили мимо детектора).
FAKEIP_RE="198\.(18|19|20|21)\."

routes() { netstat -rn -f inet 2>/dev/null; }

# Класс A: назначение из пула fake-IP, интерфейс не utun*.
bad_dst() {
  routes | awk -v re="$FAKEIP_RE" '
    $1 ~ "^" re && $4 !~ /^utun/ { print $1, "ifc=" $4, "gw=" $2 }
  '
}

# Класс C: host-маршрут (флаг H) с явным шлюзом из пула fake-IP на не-туннельном
# интерфейсе. Строки, где назначение само в fake-IP, — это класс A, здесь
# пропускаем, чтобы не предлагать два удаления одного маршрута.
bad_gw() {
  routes | awk -v re="$FAKEIP_RE" '
    $2 ~ "^" re && $3 ~ /H/ && $4 !~ /^utun/ && $4 != "lo0" && $1 !~ "^" re {
      print $1, "ifc=" $4, "gw=" $2, "flags=" $3
    }
  '
}

list_a=$(bad_dst)
list_c=$(bad_gw)

if [ -z "$list_a" ] && [ -z "$list_c" ]; then
  echo "OK: все fakeip-маршруты идут через utun*, фантомных шлюзов нет"
  exit 0
fi

if [ -n "$list_a" ]; then
  echo "НАЙДЕНЫ битые fakeip-маршруты (назначение в пуле, не через utun*):"
  echo "$list_a"
fi

if [ -n "$list_c" ]; then
  echo "НАЙДЕНЫ host-маршруты с фантомным шлюзом из fake-IP (не через utun*):"
  echo "$list_c"
  echo "(автор записи не установлен: сначала аналитика — corp-routes-clean.sh --check)"
fi

if [ "$1" = "--sudo-cmd" ]; then
  echo
  echo "Выполнить вручную (sudo потребует пароль):"
  [ -n "$list_a" ] && echo "$list_a" | awk '{ print "  sudo route delete -host", $1 }'
  [ -n "$list_c" ] && echo "$list_c" | awk '{ print "  sudo route delete -host", $1 }'
  echo "Перед удалением проверьте, что хост сейчас доступен иначе (nc/ping),"
  echo "и снимите снимок таблицы: netstat -rn -f inet > /tmp/routes-before.txt"
fi
exit 1
